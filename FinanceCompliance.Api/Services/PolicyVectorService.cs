        //La versioen precedente dle metodo spezzava i chunk ogni 50 caratteri...

        private List<string> SplitIntoChunks(string text, int maxChunkLength = 500)
        {
            var chunks = new List<string>();
            if (string.IsNullOrWhiteSpace(text)) return chunks;

            // Pulizia preliminare degli spazi multipli
            text = System.Text.RegularExpressions.Regex.Replace(text, @"\s+", " ").Trim();

            int index = 0;
            while (index < text.Length)
            {
                int length = Math.Min(maxChunkLength, text.Length - index);

                // Se non siamo arrivati alla fine del testo, cerchiamo l'ultimo spazio 
                // prima del limite per non tagliare le parole a metà.
                if (index + length < text.Length)
                {
                    int lastSpace = text.LastIndexOf(' ', index + length, length);
                    if (lastSpace > index)
                    {
                        length = lastSpace - index;
                    }
                }

                var chunk = text.Substring(index, length).Trim();
                if (!string.IsNullOrEmpty(chunk))
                {
                    chunks.Add(chunk);
                }

                //index
                index += length;
            }

            return chunks;
        } 


        public async Task<List<RetrievedContext>> SearchRelevantPoliciesAsync(string queryText)
        {
            Console.WriteLine($"[QDRANT RAG SEARCH] Ricerca semantica avviata per: '{queryText}'");

            try
            {
                /* // NOTA: Attualmente, poiché in fase di ingestion abbiamo utilizzato vettori casuali (dummy),
                 // generiamo un vettore di query coerente a 1536 dimensioni. 
                 // (Quando integrerai gli embedding reali di Ollama/Semantic Kernel, qui genererai l'embedding della query).
                 var random = new Random(queryText.GetHashCode()); // Seed deterministico basato sul testo della query
                 var queryVector = Enumerable.Range(0, 1536).Select(_ => (float)random.NextDouble()).ToArray();

                 // Eseguiamo la ricerca semantica su Qdrant restituendo i primi 3 risultati più vicini
                 var searchResults = await _qdrantClient.SearchAsync(
                     collectionName: _collectionName,
                     vector: queryVector,
                     limit: 3
                 );*/

                // GENERAZIONE EMBEDDING REALE PER LA QUERY DI RICERCA
                var queryVector = await GetEmbeddingAsync(queryText);

                // Ricerca vettoriale su Qdrant (Cosine Similarity)
                var searchResults = await _qdrantClient.SearchAsync(
                    collectionName: _collectionName,
                    vector: queryVector,
                    limit: 3
                );

                var relevantPolicies = new List<RetrievedContext>();

                foreach (var hit in searchResults)
                {
                    // Estraiamo il testo originale salvato nel Payload durante l'ingestion
                    var fileName = hit.Payload.TryGetValue("file_name", out var fileValue)
                        ? fileValue.StringValue
                        : string.Empty;
                    var chunkIndex = hit.Payload.TryGetValue("chunk_index", out var chunkValue)
                        ? chunkValue.IntegerValue
                        : 0;

                    Console.WriteLine($"[DEBUG] Chunk trovato con Score: {hit.Score} da file: {fileName}");
                    if (hit.Payload.TryGetValue("content", out var contentValue))
                    {
                        relevantPolicies.Add(new RetrievedContext
                        {
                            Content = contentValue.StringValue,
                            FileName = fileName,
                            ChunkIndex = (int)chunkIndex,
                            Score = hit.Score
                        });
                    }
                }

                if (relevantPolicies.Count == 0)
                {
                    relevantPolicies.Add(new RetrievedContext
                    {
                        Content = "Nessuna policy specifica trovata nel database vettoriale per questa richiesta.",
                        FileName = "Nessun documento",
                        ChunkIndex = 0,
                        Score = 0
                    });
                }

                Console.WriteLine($"[QDRANT RAG SEARCH] Trovati {relevantPolicies.Count} chunk pertinenti via Cosine Similarity..");
                return relevantPolicies;
            }
            catch (Exception ex)
            {
                Console.WriteLine($"[QDRANT SEARCH ERROR] Errore durante la ricerca su Qdrant: {ex.Message}");
                return new List<RetrievedContext>
                {
                    new RetrievedContext
                    {
                        Content = "Errore nel recupero delle policy di sicurezza.",
                        FileName = "Errore retrieval",
                        ChunkIndex = 0,
                        Score = 0
                    }
                };
            }
        }

