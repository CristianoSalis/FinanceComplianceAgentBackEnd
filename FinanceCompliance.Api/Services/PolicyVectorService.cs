using FinanceCompliance.Api.Models;
using Qdrant.Client;
using Qdrant.Client.Grpc;
using System.Text;
using UglyToad.PdfPig;

namespace FinanceCompliance.Api.Services
{
    public class PolicyVectorService
    {
        private readonly QdrantClient _qdrantClient;
        private readonly string _collectionName = "compliance_policies";
        private readonly string _pdfFolderPath;

        public PolicyVectorService(IWebHostEnvironment env)
        {
            //Connecting to the Qdrant container on Docker (gRPC port 6334)
            _qdrantClient = new QdrantClient("localhost", 6334);
            _pdfFolderPath = Path.Combine(env.ContentRootPath, "PoliciesPdf");
        }

        public async Task SeedPoliciesAsync()
        {
            try
            {
                var collections = await _qdrantClient.ListCollectionsAsync();
                if (!collections.Contains(_collectionName))
                {
                    await _qdrantClient.CreateCollectionAsync(_collectionName, new VectorParams
                    {
                        Size = 1536, //Standard vector dimension
                        Distance = Distance.Cosine
                    });

                    Console.WriteLine($"[QDRANT DEBUG] Collezione '{_collectionName}' creata con successo.");
                }

                if (Directory.Exists(_pdfFolderPath))
                {
                    var pdfFiles = Directory.GetFiles(_pdfFolderPath, "*.pdf");
                    foreach (var filePath in pdfFiles)
                    {
                        await ProcessAndStorePdfAsync(filePath);
                    }
                }
                else
                {
                    Directory.CreateDirectory(_pdfFolderPath);
                    Console.WriteLine($"[RAG SYSTEM] Cartella 'PoliciesPdf' creata in {_pdfFolderPath}.");
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"[QDRANT ERROR] Impossibile inizializzare Qdrant: {ex.Message}");
            }
        }

        public async Task ProcessAndStorePdfAsync(string filePath)
        {
            var fileName = Path.GetFileName(filePath);
            Console.WriteLine($"[RAG INGESTION] Elaborazione del file PDF: {fileName}");

            if (!File.Exists(filePath)) return;

            try
            {
                //Extracting text with PdfPig
                using var pdf = PdfDocument.Open(filePath);
                var sb = new StringBuilder();
                foreach (var page in pdf.GetPages())
                {
                    sb.AppendLine(page.Text);
                }
                string fullText = sb.ToString();

                //Chunking: We divide the text into blocks of approximately 500 characters
                var chunks = SplitIntoChunks(fullText, 500);
                var points = new List<PointStruct>();

                var random = new Random();

                for (int i = 0; i < chunks.Count; i++)
                {
                    //generate a unique ID for the point
                    var pointId = (ulong)Guid.NewGuid().GetHashCode();

                    // NOTE: Here, we are temporarily generating a random 1536-dimensional vector
                    // (later, we will replace it with the actual embedding generated by Ollama/Semantic Kernel)
                    var dummyVector = Enumerable.Range(0, 1536).Select(_ => (float)random.NextDouble()).ToArray();

                    //Creating a Qdrant point with payload (text and metadata)
                    var point = new PointStruct
                    {
                        Id = pointId,
                        Vectors = dummyVector,
                        Payload =
                        {
                            ["file_name"] = fileName,
                            ["chunk_index"] = i,
                            ["content"] = chunks[i]
                        }
                    };

                    points.Add(point);
                }

                //Upsert to Qdrant: Actually saving the points into the vector database
                if (points.Count > 0)
                {
                    await _qdrantClient.UpsertAsync(_collectionName, points);
                    Console.WriteLine($"[QDRANT UPSERT] Salvati con successo {points.Count} chunk dal file '{fileName}' nella collection '{_collectionName}'.");
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"[RAG ERROR] Errore durante l'elaborazione del PDF {fileName}: {ex.Message}");
            }
        }

        private List<string> SplitIntoChunks(string text, int maxChunkLength)
        {
            var chunks = new List<string>();
            if (string.IsNullOrWhiteSpace(text)) return chunks;

            int index = 0;
            while (index < text.Length)
            {
                int length = Math.Min(maxChunkLength, text.Length - index);
                chunks.Add(text.Substring(index, length).Trim());
                index += maxChunkLength;
            }
            return chunks;
        }

        public async Task<List<string>> SearchRelevantPoliciesAsync(string queryText)
        {
            await Task.Delay(50);
            Console.WriteLine($"[QDRANT RAG DEBUG] Ricerca semantica avviata per: '{queryText}'");

            //Next will perform the actual vector search (SearchAsync) on Qdrant.
            return new List<string>
            {
                "Policy estratta da Qdrant - Sezione AML: Verifica obbligatoria per importi superiori a 5.000 EUR.",
                "Policy estratta da Qdrant - Esposizione: Limite massimo di 50.000 EUR per clienti High Risk."
            };
        }
    }
}