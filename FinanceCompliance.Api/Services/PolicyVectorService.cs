                    {
                        Size = _size,
                        Distance = Distance.Cosine
                    });

                    Console.WriteLine($"[QDRANT DEBUG] Collezione '{_collectionName}' creata con successo con dimensione '{_size}'.");
                }

                if (Directory.Exists(_pdfFolderPath))
                {
                    var pdfFiles = Directory.GetFiles(_pdfFolderPath, "*.pdf");
                    foreach (var filePath in pdfFiles)
                    {
                        await ProcessAndStorePdfAsync(filePath);
                    }
                }
                else
                {
                    Directory.CreateDirectory(_pdfFolderPath);
                    Console.WriteLine($"[RAG SYSTEM] Cartella 'PoliciesPdf' creata in {_pdfFolderPath}.");
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"[QDRANT ERROR] Impossibile inizializzare Qdrant: {ex.Message}");
            }
        }

        public async Task ProcessAndStorePdfAsync(string filePath)
        {
            var fileName = Path.GetFileName(filePath);
            Console.WriteLine($"[RAG INGESTION] Elaborazione del file PDF: {fileName}");

            if (!File.Exists(filePath)) return;

            try
            {
                //Extracting text with PdfPig
                using var pdf = PdfDocument.Open(filePath);
                var sb = new StringBuilder();
                foreach (var page in pdf.GetPages())
                {
                    sb.AppendLine(page.Text);
                }
                string fullText = sb.ToString();

                //Chunking: We divide the text into blocks of approximately 500 characters
                var chunks = SplitIntoChunks(fullText, 500);
                var points = new List<PointStruct>();

                var random = new Random();

                for (int i = 0; i < chunks.Count; i++)
                {
                    var chunkText = chunks[i];
                    if (string.IsNullOrWhiteSpace(chunkText)) continue;

                    // GENERAZIONE EMBEDDING REALE VIA OLLAMA
                    var realVector = await GetEmbeddingAsync(chunkText);

                    //generate a unique ID for the point
                    var pointId = (ulong)Guid.NewGuid().GetHashCode();

/*                    // NOTE: Here, we are temporarily generating a random 1536-dimensional vector
                    // (later, we will replace it with the actual embedding generated by Ollama/Semantic Kernel)
                    var dummyVector = Enumerable.Range(0, 1536).Select(_ => (float)random.NextDouble()).ToArray();*/


                    //Creating a Qdrant point with payload (text and metadata)
                    var point = new PointStruct
                    {
                        Id = pointId,
                        Vectors = realVector, // dummyVector,
                        Payload =
                        {
                            ["file_name"] = fileName,
                            ["chunk_index"] = i,
                            ["content"] = chunkText //chunks[i]
