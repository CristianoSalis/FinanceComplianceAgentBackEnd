        /// <summary>
        /// Genera l'embedding vettoriale reale chiamando l'endpoint di Ollama locale.
        /// </summary>
        private async Task<float[]> GetEmbeddingAsync(string text)
        {
            var requestBody = new
            {
                model = _embeddingModel,
                prompt = text
            };

            var response = await _httpClient.PostAsJsonAsync(_ollamaEmbeddingUrl, requestBody);

            if (!response.IsSuccessStatusCode)
            {
                throw new Exception($"Errore API Ollama Embeddings ({response.StatusCode}): {response.ReasonPhrase}");
            }

            var result = await response.Content.ReadFromJsonAsync<OllamaEmbeddingResponse>();

            if (result?.Embedding == null || result.Embedding.Count == 0)
            {
                throw new Exception("L'API di Ollama ha restituito un vettore vuoto.");
            }

            return result.Embedding.Select(x => (float)x).ToArray();
        }


